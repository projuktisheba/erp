// Sort countries alphabetically
window.COUNTRY_LIST.sort((a, b) => a.name.localeCompare(b.name));

// Get countries grouped by starting alphabet
window.getGroupedCountries = function (filterQuery = "") {
  const query = filterQuery.toLowerCase().trim();
  const filtered = window.COUNTRY_LIST.filter(c => 
    c.name.toLowerCase().includes(query) ||
    c.code.includes(query) ||
    c.iso.toLowerCase().includes(query)
  );

  const groups = {};
  filtered.forEach(country => {
    const letter = country.name.charAt(0).toUpperCase();
    if (!groups[letter]) groups[letter] = [];
    groups[letter].push(country);
  });

  return groups;
};

// Returns an HTML string rendering a real SVG/PNG country flag graphic
window.getFlagImgHtml = function (iso, name = "") {
  if (!iso) return "";
  const code = iso.toLowerCase();
  return `<img src="https://flagcdn.com/20x15/${code}.png" srcset="https://flagcdn.com/40x30/${code}.png 2x" width="20" height="15" alt="${name || iso}" class="rounded-xs object-cover border border-slate-200 inline-block shrink-0">`;
};
